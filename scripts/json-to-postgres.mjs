const rows = [];

const insertUsers = () => {
  for (const item of readJson('users.json')) {
    rows.push(`insert into users (id, name, email, password_hash, phone, address, created_at, is_premium, premium_since, subscription, is_admin, is_veterinarian, is_verified_veterinarian, veterinarian_details, coupons, rejected_requests, raw_data) values (${[
      qNumber(item.id), q(item.name), q(item.email), q(item.password), q(item.phone), q(item.address), qDate(item.createdAt),
      qBool(item.isPremium), qDate(item.premiumSince), qJson(item.subscription), qBool(item.isAdmin), qBool(item.isVeterinarian),
      qBool(item.isVerifiedVeterinarian), qJson(item.veterinarianDetails), qArrayJson(item.coupons), qArrayJson(item.rejectedRequests), qJson(item)
    ].join(', ')}) on conflict (id) do update set name = excluded.name, email = excluded.email, password_hash = excluded.password_hash, phone = excluded.phone, address = excluded.address, created_at = excluded.created_at, is_premium = excluded.is_premium, premium_since = excluded.premium_since, subscription = excluded.subscription, is_admin = excluded.is_admin, is_veterinarian = excluded.is_veterinarian, is_verified_veterinarian = excluded.is_verified_veterinarian, veterinarian_details = excluded.veterinarian_details, coupons = excluded.coupons, rejected_requests = excluded.rejected_requests, raw_data = excluded.raw_data;`);
  }
};

