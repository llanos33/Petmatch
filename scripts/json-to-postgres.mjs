const resetSequences = () => {
  const sequenceTables = [
    'users',
    'products',
    'orders',
    'invoices',
    'pets',
    'consultations',
    'reviews',
    'veterinarian_requests',
    'coupons',
  ];

  for (const tableName of sequenceTables) {
    rows.push(`select setval(pg_get_serial_sequence('${tableName}', 'id'), coalesce((select max(id) from ${tableName}), 1), true);`);
  }
};

