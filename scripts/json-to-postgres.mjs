import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const dataDir = path.join(rootDir, 'backend', 'data');
const dbDir = path.join(rootDir, 'backend', 'db');

const readJson = (fileName) => {
  const filePath = path.join(dataDir, fileName);
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
};

const q = (value) => {
  if (value === undefined || value === null || value === '') return 'NULL';
  return `'${String(value).replaceAll("'", "''")}'`;
};

const qJson = (value) => {
  if (value === undefined || value === null) return "'{}'::jsonb";
  return `${q(JSON.stringify(value))}::jsonb`;
};

const qArrayJson = (value) => qJson(Array.isArray(value) ? value : []);
const qBool = (value, fallback = false) => value === undefined || value === null ? String(fallback) : String(Boolean(value));
const qNumber = (value) => value === undefined || value === null || value === '' ? 'NULL' : Number(value);
const qDate = (value) => q(value);

